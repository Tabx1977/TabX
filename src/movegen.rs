//! Legal move generation.
//!
//! Moves are generated legal from the start using the check, pin and threat
//! information that `Position` maintains, so there is no make-and-verify step.
//! Generation is split into "noisy" moves (captures, en passant, queen
//! promotions) and "quiet" moves (everything else, including castling and
//! non-capturing under-promotions) so the search can stage them.

use crate::attacks::*;
use crate::position::Position;
use crate::types::PieceType::*;
use crate::types::*;
use std::ops::{Deref, DerefMut};

pub const MAX_MOVES: usize = 256;

/// Fixed-capacity move list living on the stack (the most moves any legal
/// chess position can have is 218).
pub struct MoveList {
    moves: [Move; MAX_MOVES],
    len: usize,
}

impl MoveList {
    #[inline(always)]
    pub fn new() -> MoveList {
        MoveList { moves: [Move::NONE; MAX_MOVES], len: 0 }
    }

    #[inline(always)]
    pub fn push(&mut self, mv: Move) {
        self.moves[self.len] = mv;
        self.len += 1;
    }

    #[inline(always)]
    pub fn clear(&mut self) {
        self.len = 0;
    }
}

impl Deref for MoveList {
    type Target = [Move];

    #[inline(always)]
    fn deref(&self) -> &[Move] {
        &self.moves[..self.len]
    }
}

impl DerefMut for MoveList {
    #[inline(always)]
    fn deref_mut(&mut self) -> &mut [Move] {
        &mut self.moves[..self.len]
    }
}

/// All legal moves.
pub fn generate_all(pos: &Position, list: &mut MoveList) {
    generate::<true, true>(pos, list);
}

/// Legal captures, en passant captures and queen promotions.
pub fn generate_noisy(pos: &Position, list: &mut MoveList) {
    generate::<true, false>(pos, list);
}

/// Legal moves that are not generated by `generate_noisy`.
pub fn generate_quiet(pos: &Position, list: &mut MoveList) {
    generate::<false, true>(pos, list);
}

#[inline(always)]
fn shift(bb: Bitboard, delta: i32) -> Bitboard {
    if delta > 0 { Bitboard(bb.0 << delta) } else { Bitboard(bb.0 >> -delta) }
}

#[inline(always)]
fn generate<const NOISY: bool, const QUIET: bool>(pos: &Position, list: &mut MoveList) {
    let us = pos.stm();
    let ours = pos.by_color(us);
    let theirs = pos.by_color(!us);
    let occ = ours | theirs;
    let empty = !occ;
    let ksq = pos.king_sq(us);
    let checkers = pos.checkers();
    let pinned = pos.pinned();

    // King: any adjacent square that is not attacked.
    let king_targets = king_attacks(ksq) & !ours & !pos.threats();
    if NOISY {
        for to in king_targets & theirs {
            list.push(Move::new(ksq, to, Move::CAPTURE));
        }
    }
    if QUIET {
        for to in king_targets & empty {
            list.push(Move::new(ksq, to, Move::QUIET));
        }
    }

    // In double check only the king can move.
    if checkers.more_than_one() {
        return;
    }
    // In single check every other piece must capture the checker or block it.
    let check_mask =
        if checkers.any() { between(ksq, checkers.lsb()) | checkers } else { Bitboard::ALL };

    let mut targets = Bitboard::EMPTY;
    if NOISY {
        targets |= theirs;
    }
    if QUIET {
        targets |= empty;
    }
    targets &= check_mask;

    // A pinned knight can never move.
    for from in pos.pieces(us, Knight) & !pinned {
        for to in knight_attacks(from) & targets {
            let flag = if theirs.contains(to) { Move::CAPTURE } else { Move::QUIET };
            list.push(Move::new(from, to, flag));
        }
    }

    let queens = pos.pieces(us, Queen);
    for (is_bishop, sliders) in
        [(true, pos.pieces(us, Bishop) | queens), (false, pos.pieces(us, Rook) | queens)]
    {
        for from in sliders {
            let mut attacks =
                if is_bishop { bishop_attacks(from, occ) } else { rook_attacks(from, occ) };
            attacks &= targets;
            if pinned.contains(from) {
                attacks &= line(ksq, from);
            }
            for to in attacks {
                let flag = if theirs.contains(to) { Move::CAPTURE } else { Move::QUIET };
                list.push(Move::new(from, to, flag));
            }
        }
    }

    // Pawns.
    let (up, promo_rank, double_rank): (i32, Bitboard, Bitboard) = match us {
        Color::White => (8, Bitboard::rank(6), Bitboard::rank(2)),
        Color::Black => (-8, Bitboard::rank(1), Bitboard::rank(5)),
    };
    let pawns = pos.pieces(us, Pawn);
    let promo_pawns = pawns & promo_rank;
    let other_pawns = pawns & !promo_rank;
    let pin_ok = |from: Square, to: Square| !pinned.contains(from) || line(ksq, from).contains(to);
    // Capture directions: towards the a-file and towards the h-file.
    let capture_dirs = [(up - 1, !Bitboard::FILE_A), (up + 1, !Bitboard::FILE_H)];

    if QUIET {
        let single = shift(other_pawns, up) & empty;
        let double = shift(single & double_rank, up) & empty & check_mask;
        for to in single & check_mask {
            let from = to.offset(-up);
            if pin_ok(from, to) {
                list.push(Move::new(from, to, Move::QUIET));
            }
        }
        for to in double {
            let from = to.offset(-2 * up);
            if pin_ok(from, to) {
                list.push(Move::new(from, to, Move::DOUBLE_PUSH));
            }
        }
    }
    if NOISY {
        for (delta, mask) in capture_dirs {
            for to in shift(other_pawns & mask, delta) & theirs & check_mask {
                let from = to.offset(-delta);
                if pin_ok(from, to) {
                    list.push(Move::new(from, to, Move::CAPTURE));
                }
            }
        }
    }
    if promo_pawns.any() {
        for to in shift(promo_pawns, up) & empty & check_mask {
            let from = to.offset(-up);
            if pin_ok(from, to) {
                if NOISY {
                    list.push(Move::new(from, to, Move::PROMO_QUEEN));
                }
                if QUIET {
                    for promo in (0..3).rev() {
                        list.push(Move::new(from, to, Move::PROMO + promo));
                    }
                }
            }
        }
        if NOISY {
            for (delta, mask) in capture_dirs {
                for to in shift(promo_pawns & mask, delta) & theirs & check_mask {
                    let from = to.offset(-delta);
                    if pin_ok(from, to) {
                        for promo in (0..4).rev() {
                            list.push(Move::new(from, to, Move::PROMO + Move::CAPTURE + promo));
                        }
                    }
                }
            }
        }
    }
    if NOISY && pos.ep() != Square::NONE {
        for from in pawn_attacks(!us, pos.ep()) & pawns {
            if pos.ep_is_legal(from) {
                list.push(Move::new(from, pos.ep(), Move::EN_PASSANT));
            }
        }
    }

    // Castling, encoded as the king moving onto its own rook.
    if QUIET && checkers.is_empty() {
        for kingside in [true, false] {
            if pos.castle_is_legal(kingside) {
                list.push(Move::new(ksq, pos.castle_rook(us, kingside), Move::CASTLE));
            }
        }
    }
}

/// Counts leaf nodes of the legal move tree to the given depth.
pub fn perft(pos: &Position, depth: u32) -> u64 {
    if depth == 0 {
        return 1;
    }
    let mut list = MoveList::new();
    generate_all(pos, &mut list);
    if depth == 1 {
        return list.len() as u64;
    }
    let mut nodes = 0;
    for &mv in list.iter() {
        let mut next = *pos;
        next.make_move(mv);
        nodes += perft(&next, depth - 1);
    }
    nodes
}

/// Parses a move in UCI notation against the legal moves of `pos`. Castling is
/// accepted both as the king's two-square move and as king-takes-rook.
pub fn parse_uci_move(pos: &Position, text: &str) -> Option<Move> {
    let mut list = MoveList::new();
    generate_all(pos, &mut list);
    list.iter().copied().find(|mv| mv.to_uci(false) == text || mv.to_uci(true) == text)
}
